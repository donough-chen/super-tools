/** 通用 HTTP 状态码兜底 */
const HTTP_MAP: Record<number, string> = {
  400: '请求参数有误',
  401: '未登录或登录已过期',
  403: '无权限访问',
  404: '资源不存在',
  422: '请求参数校验失败',
  429: '请求过于频繁，请稍后再试',
  500: '服务器开小差了，请稍后再试',
  502: '网络异常，请稍后再试',
  503: '服务暂不可用，请稍后再试',
  504: '网关超时，请稍后再试',
};

/**
 * 根据后端 code 或 HTTP 状态码映射友好文案
 * @param code 后端业务错误码（如 100303）或 HTTP 状态码（如 429）
 * @param defaultMsg 兜底文案（如未匹配，则返回此值或 '操作失败'）
 */
export const mapErrorCode = (code?: number, defaultMsg = '操作失败'): string => {
  if (!code) return defaultMsg;
  return CODE_MAP[code] || HTTP_MAP[code] || defaultMsg;
};
